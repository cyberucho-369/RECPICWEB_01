#!/usr/bin/env python3
"""Generate static (crawlable) portfolio cards into portfolio/index.html.

The portfolio grid is normally built client-side by script.js, which fetches
assets/portfolio/manifest.json and each folder's info.txt. That leaves the grid
empty in the raw HTML, so search engines see no project content at all —
which is why /portfolio/ fell out of Google's index.

This script pre-renders the same cards as static HTML between marker comments.
script.js clears the grid before injecting its interactive cards, so the static
markup serves crawlers and no-JS visitors only and is never shown twice.

Run after adding or renaming anything under assets/portfolio/:
    python3 execution/build_portfolio_static.py
"""
import html
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets" / "portfolio"
PAGE = ROOT / "portfolio" / "index.html"

# script.js shows only folders numbered >= 7; 01-06 live on the home page.
MIN_SORT = 7

START = "<!-- PF_STATIC_START - generated by execution/build_portfolio_static.py; do not edit by hand -->"
END = "<!-- PF_STATIC_END -->"
PLACEHOLDER = "<!-- Cards injected dynamically by script.js -->"
ANCHOR = '<div id="portfolio-page-grid" class="portfolio-page-grid">'


def folder_num(name):
    m = re.match(r"\s*(\d+)", name)
    return int(m.group(1)) if m else 0


def parse_info(path):
    lines = [l.strip() for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]
    if not lines:
        return None
    tag, ratio = "", "16:9"
    for line in lines:
        m = re.match(r"tag:\s*(.+)", line, re.I)
        if m:
            tag = m.group(1).strip().lower()
        m = re.match(r"ratio:\s*(\d+:\d+)", line, re.I)
        if m:
            ratio = m.group(1)
    return {"title": lines[0], "tag": tag, "ratio": ratio}


def build_items():
    manifest = json.loads((ASSETS / "manifest.json").read_text(encoding="utf-8"))
    items = []
    for folder in manifest:
        num = folder_num(folder)
        if num < MIN_SORT:
            continue
        info_path = ASSETS / folder / "info.txt"
        if not info_path.is_file():
            print("  skip (no info.txt): %s" % folder, file=sys.stderr)
            continue
        info = parse_info(info_path)
        if not info:
            continue
        info.update(id=folder, num=num)
        items.append(info)
    items.sort(key=lambda i: i["num"], reverse=True)
    return items


def card_html(item):
    title = html.escape(item["title"], quote=True)
    tag = html.escape(item["tag"], quote=True)
    src = html.escape("/assets/portfolio/%s/thumb.jpg" % item["id"], quote=True)
    portrait = " pf-video-card--portrait" if item["ratio"] == "9:16" else ""
    return "\n".join([
        '            <div class="pf-video-card%s" data-tag="%s">' % (portrait, tag),
        '                <img class="pf-thumbnail-img" src="%s" alt="%s" loading="lazy">' % (src, title),
        '                <div class="pf-card-overlay">',
        '                    <div class="pf-card-info">',
        '                        <h3 class="pf-card-title">%s</h3>' % title,
        '                    </div>',
        '                </div>',
        '                <div class="pf-play-btn">',
        '                    <svg viewBox="0 0 24 24"><path d="M8 5v14l11-7z"/></svg>',
        '                </div>',
        '            </div>',
    ])


def main():
    items = build_items()
    if not items:
        print("No portfolio items found - aborting without changes.", file=sys.stderr)
        return 1

    block = "\n".join(
        ["            " + START] + [card_html(i) for i in items] + ["            " + END]
    )
    page = PAGE.read_text(encoding="utf-8")

    if START in page and END in page:
        pattern = re.compile(r"[ \t]*" + re.escape(START) + r".*?" + re.escape(END), re.S)
        page = pattern.sub(lambda _: block, page, count=1)
    elif PLACEHOLDER in page:
        page = page.replace(" " * 12 + PLACEHOLDER, block, 1)
    elif ANCHOR in page:
        page = page.replace(ANCHOR, ANCHOR + "\n" + block, 1)
    else:
        print("Could not find #portfolio-page-grid - aborting.", file=sys.stderr)
        return 1

    PAGE.write_text(page, encoding="utf-8")
    print("Wrote %d static portfolio cards into %s" % (len(items), PAGE.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
